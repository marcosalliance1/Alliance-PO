import type { ItemCatalogo } from '../types'
import { v4 as uuid } from '../utils/uuid'

function item(
  area: string,
  subcategoria: string,
  nome: string,
  secoes: string[],
  tipos: ItemCatalogo['tiposEscolaAplicavel'],
  fornecedor = '',
  tipoCusto: ItemCatalogo['tipoCusto'] = 'Custo Fixo',
  valorRef = 0,
): ItemCatalogo {
  return {
    id: uuid(),
    codigo: '',
    area,
    subcategoria,
    item: nome,
    fornecedorPadrao: fornecedor,
    tipoCusto,
    valorUnitarioReferencia: valorRef,
    secaoAplicavel: secoes,
    tiposEscolaAplicavel: tipos,
    ativo: true,
  }
}

